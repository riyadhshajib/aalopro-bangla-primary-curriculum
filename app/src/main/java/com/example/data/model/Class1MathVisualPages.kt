    private val ranges = listOf(
        8..11, 12..15, 16..35, 36..49, 50..60, 61..64,
        65..72, 73..75, 76..80, 81..85, 86..88, 89..92,
        93..98, 99..103, 104..107, 108..111, 112..115, 116..122
    )

    fun forTopic(topicIndex: Int, verified: List<VisualExercise>): List<VisualExercise> {
        val range = ranges.getOrNull(topicIndex) ?: return verified
        val verifiedByPage = verified.mapNotNull { item ->
            pageNumber(item.sourceBangla)?.let { it to item }
        }.toMap()
        return range.map { page ->
            verifiedByPage[page] ?: VisualExercise(
                imageResId = pageResources[page - 8],
                questionBangla = "পৃষ্ঠা ${banglaNumber(page)}-এর ছবি ও নির্দেশনা মন দিয়ে দেখো। কী দেখা যাচ্ছে এবং কী করতে বলা হয়েছে নিজের ভাষায় বলো।",
                answerBangla = "করণীয়: ছবির প্রতিটি অংশ বাম থেকে ডানে দেখো। বস্তু থাকলে একটি করে গুনে সংখ্যা বলো; মিল করতে বললে একই সংখ্যা বা বৈশিষ্ট্যের জোড়া খুঁজো; আঁকা বা রং করার কাজ হলে বইয়ের নির্দেশনা অনুসরণ করে নিজে সম্পন্ন করো। শেষে আবার গুনে বা মিলিয়ে যাচাই করো।",
                sourceBangla = "প্রথম শ্রেণির প্রাথমিক গণিত, ২০২৬ শিক্ষাবর্ষ, PDF পৃষ্ঠা ${banglaNumber(page)}"
            )
        }
    }

    private fun pageNumber(source: String): Int? {
        val value = Regex("(?:পৃষ্ঠা|page)\\s*([০-৯0-9]+)", RegexOption.IGNORE_CASE)
            .find(source)?.groupValues?.getOrNull(1) ?: return null
        return value.map { digit ->
            if (digit in '০'..'৯') ('0'.code + digit.code - '০'.code).toChar() else digit
        }.joinToString("").toIntOrNull()
    }

    private fun banglaNumber(value: Int): String = value.toString().map { digit ->
        if (digit in '0'..'9') ('০'.code + digit.code - '0'.code).toChar() else digit
    }.joinToString("")
}

