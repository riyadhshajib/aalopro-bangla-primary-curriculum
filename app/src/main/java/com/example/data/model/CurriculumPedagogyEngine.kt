                            "সংখ্যার মাঝে শূন্য (০) থাকলে স্থানীয় মান গণনায় শূন্যের ঘরটি এড়িয়ে যাওয়া (যেমন: ৩০৫ কে পঁয়ত্রিশ পড়া)।",
