package com.example.data.model

/**
 * Pedagogical Research Engine for NCTB Bangladesh Primary Curriculum (Class 1 to 5).
 * Generates dynamically researched:
 * 1. Topic-specific Teaching Strategies for Parents & Teachers (শিক্ষক ও অভিভাবক পাঠদান কৌশল)
 * 2. Real Common Mistakes & Remedial Warnings (বাচ্চারা যেসব সুনির্দিষ্ট ভুল করে ও প্রতিকার)
