object CurriculumPedagogyEngine {

    data class TopicPedagogy(
        val teachingTips: List<String>,
        val commonMistakes: List<String>,
        val homeActivity: String,
        val oralQuestions: List<TopicQA>
    )

    fun getPedagogyForTopic(
        classLevelNumber: Int,
        subjectName: String,
        topic: CurriculumTopic
    ): TopicPedagogy {
        val title = topic.titleBangla.lowercase()
        val summary = topic.summaryBangla.lowercase()
        val subject = subjectName.lowercase()

        // Fully expanded Class One books carry their own age-appropriate,
        // chapter-specific guide. Prefer it over the older broad templates,
        // which also contain upper-primary techniques such as carrying and borrowing.
        if (classLevelNumber == 1 && topic.parentTeachingTips.isNotEmpty()) {
            return TopicPedagogy(
                teachingTips = topic.parentTeachingTips,
                commonMistakes = topic.commonMistakes.ifEmpty { listOf("শিশুকে উত্তর বলে দেওয়া, কিন্তু নিজে চেষ্টা করার সময় না দেওয়া।") },
