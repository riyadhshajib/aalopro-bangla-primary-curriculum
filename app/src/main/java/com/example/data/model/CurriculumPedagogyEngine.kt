                    TopicPedagogy(
                        teachingTips = listOf(
                            "কাঠি বা মার্বেলের ১০টির বান্ডিল তৈরি করে 'দশক' এবং একক কাঠি দিয়ে 'একক' বাস্তব রূপ দেখান।",
                            "স্থানীয় মানের ছক (একক, দশক, শতক, হাজার, লক্ষ, কোটি) খাতায় এঁকে যেকোনো সংখ্যার ঘরে অঙ্ক বসিয়ে মান নির্ণয় করান।",
                            "কমা (,) বসানোর নিয়ম শেখান: ১ম কমা ডান দিক থেকে ৩ অঙ্ক পর, এরপর প্রতি ২ অঙ্ক পর পর কমা বসে।"
                        ),
