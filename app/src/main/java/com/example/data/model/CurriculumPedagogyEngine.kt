                            TopicQA("৩ অঙ্ক বিশিষ্ট ক্ষুদ্রতম ও বৃহত্তম সংখ্যা কী কী?", "ক্ষুদ্রতম সংখ্যা ১০০ এবং বৃহত্তম সংখ্যা ৯৯৯।")
