                        ),
                        homeActivity = "১০টি করে দিয়াশলাইয়ের কাঠি সুতা দিয়ে বেঁধে ৫টি বান্ডিল ও ৩টি খোলা কাঠি দিয়ে ৫৩ সংখ্যাটি তৈরি করতে বলুন।",
