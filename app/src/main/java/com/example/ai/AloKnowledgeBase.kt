    fun findLesson(query: String): TopicLesson? {
        val q = query.lowercase().trim()
        
        // Priority 1: Match longest keywords on raw query first
        var bestLesson: TopicLesson? = null
        var maxMatchLen = 0

        for (lesson in lessons) {
            for (kw in lesson.keywords) {
                val kwLower = kw.lowercase()
                if (q.contains(kwLower)) {
                    if (kwLower.length > maxMatchLen) {
                        maxMatchLen = kwLower.length
                        bestLesson = lesson
                    }
                }
            }
        }

        if (bestLesson != null) return bestLesson

        // Priority 2: Banglish normalizer check with length priority
        val banglishResult = AloBanglishNormalizer.normalizeBanglish(query)
        if (banglishResult.isBanglish) {
            val normalizedQ = banglishResult.convertedBanglaQuery.lowercase()
            for (lesson in lessons) {
                for (kw in lesson.keywords) {
                    val kwLower = kw.lowercase()
                    if (normalizedQ.contains(kwLower)) {
                        if (kwLower.length > maxMatchLen) {
                            maxMatchLen = kwLower.length
                            bestLesson = lesson
                        }
                    }
                }
            }
        }

        return bestLesson
    }
