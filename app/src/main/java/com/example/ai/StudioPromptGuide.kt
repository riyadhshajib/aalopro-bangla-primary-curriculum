    fun answerFor(query: String, parentQuestion: String? = null): String? {
        val direct = guides[normalize(query)]
        if (direct != null) return direct.answer
        if (parentQuestion != null && AloFollowUpExplainer.isFollowUpSimplificationRequest(query)) {
            return guides[normalize(parentQuestion)]?.let { "আরও সহজ করে বলি। ${it.answer}\n\n${it.followUp}" }
        }
        return null
    }

    private fun normalize(value: String) = value.trim().replace(Regex("\\s+"), " ")
